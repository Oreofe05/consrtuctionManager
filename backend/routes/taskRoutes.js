import { Router } from "express";
import { protect, authorize } from "../middleware/authMiddleware.js";
import { validateObjectId } from "../middleware/validate.js";
import { listRecords, getRecord, createRecord, updateRecord, deleteRecord, assignTask } from "../controllers/crudController.js";
const router = Router();
router.use(protect);
router.get("/", listRecords("tasks"));
router.post("/", authorize("System Administrator", "Administrator", "Project Manager"), createRecord("tasks"));
router.get("/:id", validateObjectId(), getRecord("tasks"));
router.patch("/:id", validateObjectId(), updateRecord("tasks"));
router.delete("/:id", authorize("System Administrator", "Administrator", "Project Manager"), validateObjectId(), deleteRecord("tasks"));
router.patch("/:id/assign", authorize("System Administrator", "Administrator", "Project Manager"), validateObjectId(), assignTask);
export default router;
