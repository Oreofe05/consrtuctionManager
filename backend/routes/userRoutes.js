import { Router } from "express";
import { listUsers, createUser, updateUser, deleteUser } from "../controllers/userController.js";
import { protect, authorize } from "../middleware/authMiddleware.js";
import { validateObjectId } from "../middleware/validate.js";
const router = Router();
router.use(protect);
router.post("/", authorize("System Administrator", "Administrator"), createUser);
router.get("/", authorize("System Administrator", "Administrator", "Project Manager"), listUsers);
router.patch("/:id", authorize("System Administrator", "Administrator"), validateObjectId(), updateUser);
router.delete("/:id", authorize("System Administrator", "Administrator"), validateObjectId(), deleteUser);
export default router;
