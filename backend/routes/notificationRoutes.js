import { Router } from "express";
import { protect } from "../middleware/authMiddleware.js";
import { listNotifications, markRead, markAllRead, deleteNotification } from "../controllers/notificationController.js";
import { validateObjectId } from "../middleware/validate.js";
const router = Router();
router.use(protect);
router.get("/", listNotifications);
router.patch("/read-all", markAllRead);
router.patch("/:id/read", validateObjectId(), markRead);
router.delete("/:id", validateObjectId(), deleteNotification);
export default router;
